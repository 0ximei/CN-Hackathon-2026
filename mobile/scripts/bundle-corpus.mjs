/**
 * Bakes the sample corpus into the APK.
 *
 * Read from `corpus/sources`, the authored markdown at the top of the
 * repository, rather than from the web app's `public/corpus` — that directory
 * is the *output* of the web build's own corpus step, so depending on it meant
 * this app could not be built until the other one had been. Content is worth
 * sharing between the two builds; a build artefact of one of them is not.
 *
 * A browser fetches these files over HTTP. A phone in a room with no network
 * cannot, and the whole point of the mesh is that it works there, so the same
 * files are compiled in as strings. They total about 25 KB — smaller than one
 * app icon.
 *
 * Chunking is deliberately *not* done here. `@core/lib/chunk` runs at first
 * launch instead, so a phone and a browser split the same document into exactly
 * the same chunks with the same content-addressed ids, and a chunk replicated
 * from one to the other keeps its identity.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = resolve(here, '..', '..', 'corpus', 'sources');
const outFile = resolve(here, '..', 'src', 'corpus', 'seed.ts');

const files = readdirSync(sourceDir)
  .filter((f) => f.endsWith('.md'))
  .sort();

if (!files.length) {
  console.error(`No markdown found in ${sourceDir}.`);
  process.exit(1);
}

const entries = files.map((file) => {
  const markdown = readFileSync(join(sourceDir, file), 'utf8');
  return `  {\n    file: ${JSON.stringify(file)},\n    markdown: ${JSON.stringify(markdown)},\n  },`;
});

const banner = `/**
 * GENERATED by scripts/bundle-corpus.mjs — do not edit.
 * Source: corpus/sources/*.md  (${files.length} documents)
 */

export interface SeedDoc {
  file: string;
  markdown: string;
}

export const SEED_DOCS: SeedDoc[] = [
${entries.join('\n')}
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, banner);
const bytes = entries.reduce((n, e) => n + e.length, 0);
console.log(`Bundled ${files.length} documents (~${Math.round(bytes / 1024)} KB) into src/corpus/seed.ts`);
